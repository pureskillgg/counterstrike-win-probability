import polars as pl
D = "G:/pureskill/csds-cs2/data"
grid = pl.scan_parquet(D + "/viz/per_tick_states.parquet")
pred = pl.scan_parquet(D + "/viz/per_tick_test_preds.parquet")
p1 = pl.scan_parquet(D + "/state_sample/players_1hz.parquet")
rds = pl.scan_parquet(D + "/state_sample/rounds.parquet")

g = grid.collect()
print("grid rows", g.height, "matches", g["match_key"].n_unique(), "match+round", g.select(["match_key","round"]).n_unique())
print("grid key (match,round,tick) unique:", g.select(["match_key","round","tick"]).n_unique(), "rows", g.height)
print("grid dup key rows:", g.height - g.select(["match_key","round","tick"]).n_unique())
print("rows per match+round describe:")
print(g.group_by(["match_key","round"]).len()["len"].describe())
print("tick step diffs sample:", g.filter(pl.col("match_key")==g["match_key"][0]).sort("tick")["tick"].diff().drop_nulls().unique().head(5).to_list())
print("alive_ct range", g["alive_ct"].min(), g["alive_ct"].max(), "alive_t range", g["alive_t"].min(), g["alive_t"].max())
print("label_ct_win values", g["label_ct_win"].unique().sort().to_list())
print("is_pistol_round", g["is_pistol_round"].unique().to_list(), "is_overtime", g["is_overtime"].unique().to_list())
print("seconds_since_round_live min/max", g["seconds_since_round_live"].min(), g["seconds_since_round_live"].max())
print("w_round sum per match+round (first 3):", g.group_by(["match_key","round"]).agg(pl.col("w_round").sum()).head(3))
print("n_pts == rows per match+round? ", g.group_by(["match_key","round"]).agg([pl.col("n_pts").first().alias("n"), pl.len().alias("rows")]).filter(pl.col("n")!=pl.col("rows")).height)

pr = pred.collect()
print("pred rows", pr.height, "test matches", pr["match_key"].n_unique(), "test match+round", pr.select(["match_key","round"]).n_unique())
print("pred key unique:", pr.height - pr.select(["match_key","round","tick"]).n_unique())
print("pred p_xgb_grid nulls", pr["p_xgb_grid"].null_count(), "min", pr["p_xgb_grid"].min(), "max", pr["p_xgb_grid"].max())
j = pr.join(g.select(["match_key","round","tick","alive_ct","alive_t","label_ct_win"]), on=["match_key","round","tick"], how="left", suffix="_g")
print("pred rows joined to grid: unmatched =", j.filter(pl.col("alive_ct").is_null()).height, "label mismatch =", j.filter(pl.col("label_ct_win") != pl.col("label_ct_win_g")).height)
test_keys = set(pr["match_key"].unique().to_list())
g_test = g.filter(pl.col("match_key").is_in(list(test_keys)))
print("grid rows in test matches", g_test.height, "matches", g_test["match_key"].n_unique())
print("grid rows in test matches which are in pred:", g_test.join(pr.select(["match_key","round","tick"]), on=["match_key","round","tick"], how="inner").height)

sr = rds.collect()
print("rounds rows", sr.height, "matches", sr["match_key"].n_unique(), "split values", sr["split"].unique().to_list())
print("grid matches in rounds:", len(set(g["match_key"].unique().to_list()) & set(sr["match_key"].unique().to_list())))
print("grid matches not in rounds:", len(set(g["match_key"].unique().to_list()) - set(sr["match_key"].unique().to_list())))
print("rounds split by match count:", sr.group_by("split").agg(pl.col("match_key").n_unique()))
print("grid test-match round count:", g_test.select(["match_key","round"]).n_unique())
