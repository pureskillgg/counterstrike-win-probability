import polars as pl, numpy as np
B = "G:/pureskill/csds-cs2/data"
pt = pl.read_parquet(f"{B}/viz/per_tick_states.parquet")
pr = pl.read_parquet(f"{B}/viz/per_tick_test_preds.parquet")
test_keys = pr.select("match_key").unique()
print("test matches in preds:", test_keys.height)
pt_test = pt.join(test_keys, on="match_key", how="inner")
print("grid rows in test matches:", pt_test.height, " preds rows:", pr.height)
print("preds unique (mk,round,tick):", pr.select(["match_key","round","tick"]).unique().height)
print("grid unique (mk,round,tick):", pt.select(["match_key","round","tick"]).unique().height)
j = pr.join(pt, on=["match_key","round","tick"], how="left", suffix="_g")
print("preds rows matched to grid:", j.filter(pl.col("alive_ct").is_not_null()).height, "of", pr.height)
print("label agrees preds vs grid:", j.filter(pl.col("label_ct_win")==pl.col("label_ct_win_g")).height)
print("seconds agrees:", j.filter(pl.col("seconds_since_round_live")==pl.col("seconds_since_round_live_g")).height)
print("p_xgb_grid range:", pr.select(pl.col("p_xgb_grid").min().alias("mn"), pl.col("p_xgb_grid").max().alias("mx")).row(0))
print("p_xgb_grid exact 0/1 count:", pr.filter((pl.col("p_xgb_grid")<=0)|(pl.col("p_xgb_grid")>=1)).height)
print("p nulls:", pr["p_xgb_grid"].null_count())
# grid rows per test match vs preds rows
print("grid test rows not in preds:", pt_test.join(pr.select(["match_key","round","tick"]), on=["match_key","round","tick"], how="anti").height)
# state sample overlap with grid
pl1 = pl.read_parquet(f"{B}/state_sample/players_1hz.parquet", columns=["match_key","round","seconds_since_live","split","player_id","team_code","equipment_value_calc","tick"])
rd = pl.read_parquet(f"{B}/state_sample/rounds.parquet")
sample_keys = rd.select("match_key").unique()
print("state-sample matches:", sample_keys.height, " in grid:", sample_keys.join(pt.select("match_key").unique(), on="match_key").height)
print("state-sample matches in test preds:", sample_keys.join(test_keys, on="match_key").height)
print("team_code values:", pl1.group_by("team_code").len().to_dicts())
print("seconds_since_live min/max:", pl1.select(pl.col("seconds_since_live").min().alias("mn"), pl.col("seconds_since_live").max().alias("mx")).row(0))
s0 = pl1.filter(pl.col("seconds_since_live")==0)
print("rows at second 0:", s0.height)
cnt = s0.group_by(["match_key","round","team_code"]).agg(pl.len().alias("npl"))
print("players per team at second 0 dist:", cnt.group_by("npl").agg(pl.len().alias("nteams")).sort("npl").to_dicts())
print("null equipment at second0:", s0["equipment_value_calc"].null_count())
print("equipment at second 0 describe:", s0.select(pl.col("equipment_value_calc").min().alias("mn"), pl.col("equipment_value_calc").median().alias("md"), pl.col("equipment_value_calc").max().alias("mx")).row(0))
print("rounds in sample:", rd.height, " unique (mk,round):", rd.select(["match_key","round"]).unique().height)
print("rounds.round dtype:", rd.schema["round"], "pl1 round dtype:", pl1.schema["round"])
print("ct_win vs grid label check:")
lab = pt.group_by(["match_key","round"]).agg(pl.col("label_ct_win").first())
cmp = rd.select(["match_key","round","ct_win"]).join(lab, on=["match_key","round"], how="left")
print("rounds with grid label:", cmp.filter(pl.col("label_ct_win").is_not_null()).height, "agree:", cmp.filter(pl.col("ct_win")==pl.col("label_ct_win")).height)
print("rounds.parquet alive_gap_snapshots dist:", rd.group_by("alive_gap_snapshots").len().to_dicts()[:5])
print("players_1hz rounds total:", pl1.select(["match_key","round"]).unique().height)
