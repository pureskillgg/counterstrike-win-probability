import polars as pl
d = "E:/csds_final/csds/2026/09/01/01f19adb-166f-4666-95fb-fc75f186c486"
ps = pl.read_parquet(f"{d}/player_status", columns=["tick", "round", "player_id", "second"])
rs = pl.read_parquet(f"{d}/round_state", columns=["round", "tick", "event_type"])
re_ = pl.read_parquet(f"{d}/round_end", columns=["round", "tick"])
f = rs.filter((pl.col("event_type") == "round_freeze_end") & (pl.col("round") == 6))["tick"].to_list()
e = re_.filter(pl.col("round") == 6)["tick"].to_list()
print("round 6 freeze_end ticks", f, "round_end ticks", e)
sub = ps.filter(pl.col("round") == 6)
print("rows in round 6", sub.height, "distinct ticks", sub["tick"].n_unique())
ticks = sub["tick"].unique().sort()
print("first 12 ticks", ticks.head(12).to_list())
print("first 12 ticks minus freeze", (ticks.head(12) - f[0]).to_list())
print("second values first 12 rows", sub.sort("tick").head(12)["second"].to_list())
print("per-tick player counts (first 8 ticks)", sub.group_by("tick").agg(pl.len().alias("n")).sort("tick").head(8).to_dicts())
dif = ticks.diff().drop_nulls()
print("tick spacing counts (top)", dif.value_counts().sort("count", descending=True).head(6))
print("ticks mod 64 of distinct ticks (top)", (ticks % 64).value_counts().sort("count", descending=True).head(6))
print("freeze mod 64", f[0] % 64)
