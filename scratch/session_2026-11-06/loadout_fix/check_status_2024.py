import polars as pl
P = "G:/pureskill/csds-cs2/data/status_1hz_2024/2024-02-01.parquet"
df = pl.read_parquet(P)
print("rows", df.height)
print("schema", [(c, str(t)) for c, t in df.schema.items()])
print("n_match_keys", df["match_key"].n_unique())
print("side values", df["side"].unique().sort().to_list())
print("health==0 rows", df.filter(pl.col("health") == 0).height, "of", df.height)
print("health min/max", df["health"].min(), df["health"].max())
dup = df.group_by(["match_key", "round", "tick", "player_id"]).agg(pl.len().alias("n")).filter(pl.col("n") > 1)
print("duplicate (match,round,tick,player) keys", dup.height)
res = (df.with_columns((pl.col("tick") % 64).alias("res"))
         .group_by(["match_key", "round"]).agg(pl.col("res").n_unique().alias("n_res")))
print("rounds with >1 tick residue mod 64", res.filter(pl.col("n_res") > 1).height, "of", res.height)
print("per (match,round,tick) players per side, sample")
pc = df.group_by(["match_key", "round", "tick", "side"]).agg(pl.len().alias("n"))
print(pc["n"].describe())
print("inv_primary null rows", df.filter(pl.col("inv_primary").is_null()).height)
print("armor null rows", df.filter(pl.col("armor").is_null()).height)
